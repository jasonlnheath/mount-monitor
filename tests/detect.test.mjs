// Mount Monitor block-event detection tests.
//
// Run: bash tests/run.sh   (or: node --test tests/)
//
// The guard for the captain's USB test (2026-10-26): a newly plugged drive took
// 30-60 seconds to get its notice, because the only thing that ever asked for a
// scan was the widget's own 60-second timer. The fix asks on the kernel's own
// block uevents - `udevadm monitor --kernel --subsystem-match=block` as a
// long-running process - and those decisions (the argv, what counts as a block
// event, how a burst of uevent lines coalesces into one rescan, why a second
// rescan has to follow, and how a dead monitor is restarted) live in mounts.js
// like every other decision, so they are testable without a running shell.
//
// The fixture is real `udevadm monitor` output captured on this rig as the
// ordinary user, with events generated by `udisksctl loop-setup`. The two live
// checks below re-run that against the argv the plugin actually runs, and skip
// where udevadm or udisks2 is absent.

import { test } from "node:test";
import assert from "node:assert/strict";
import { mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { spawn, spawnSync } from "node:child_process";
import os from "node:os";
import path from "node:path";
import vm from "node:vm";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const repo = path.dirname(here);

// mounts.js is a Qt-importable JavaScript file (plain top-level functions), so
// it is loaded into a VM context instead of imported as an ES module.
function loadMounts() {
  const src = readFileSync(path.join(repo, "mounts.js"), "utf8");
  const ctx = { Math, Number, parseInt, isFinite, String, Array, RegExp, JSON, Object, Date, console };
  vm.runInNewContext(src, ctx);
  return ctx;
}

const Mounts = loadMounts();

// Fixture lines starting with '#' document the fixture and are not udev lines.
function fixtureLines(name) {
  return readFileSync(path.join(here, "fixtures", name), "utf8")
    .split("\n")
    .filter((line) => line.trim() !== "" && !line.trim().startsWith("#"));
}

const UDEV = fixtureLines("udev-monitor.txt");

function strings(list) {
  // Array.from rather than list.map: the list is built inside mounts.js's VM
  // context, and a cross-realm array is not deep-equal to a local one.
  return Array.from(list, (s) => s);
}

function num(value) {
  return typeof value === "number" && isFinite(value);
}

function has(cmd) {
  return spawnSync("sh", ["-c", `command -v ${cmd}`], { encoding: "utf8" }).status === 0;
}

function sleep(ms) {
  return new Promise((resolve) => setTimeout(resolve, ms));
}

// A long-running process whose stdout is collected line by line, the way
// Quickshell's SplitParser does it for the widget.
function lineCollector(proc) {
  const state = { lines: [], stderr: "", exited: null };
  let buf = "";
  proc.stdout.on("data", (chunk) => {
    buf += chunk.toString("utf8");
    let i;
    while ((i = buf.indexOf("\n")) >= 0) {
      state.lines.push(buf.slice(0, i));
      buf = buf.slice(i + 1);
    }
  });
  proc.stderr.on("data", (chunk) => { state.stderr += chunk.toString("utf8"); });
  proc.on("exit", (code) => { state.exited = code; });
  proc.on("error", (err) => { state.exited = "spawn-error:" + err.code; });
  return state;
}

// --- the monitor command ----------------------------------------------------

test("the block monitor runs as typed argv, on the kernel source, filtered to block", () => {
  const args = strings(Mounts.udevArgs());
  assert.equal(args[0], "udevadm", "the program is udevadm");
  assert.ok(args.includes("--kernel"), "the kernel source is the earliest signal, and needs no root");
  assert.ok(args.includes("--subsystem-match=block"), "only block devices wake the widget");
  assert.ok(!args.some((a) => a.startsWith("-") && a !== args[0] && !a.startsWith("--")),
    `no short-form option guessing: ${args.join(" ")}`);
  assert.ok(!args.includes("--property") && !args.includes("-p"),
    "--property adds KEY=VALUE lines after every event; the parser would only have to ignore them");
  assert.ok(!args.some((a) => /\s/.test(a)), "typed argv: no element carries a space, no shell in sight");
  assert.ok(!args.some((a) => /[;&|`$*]/.test(a)), "no shell metacharacters in the monitor argv");
});

// --- what a udev line is, and what is not -----------------------------------

test("a real udevadm line parses into source, action, device path, and subsystem", () => {
  const event = Mounts.parseUdevEvent("KERNEL[204133.554193] add      /devices/virtual/block/loop0/loop0p1 (block)");
  assert.ok(event, "the line must parse");
  assert.equal(event.action, "add");
  assert.equal(event.devpath, "/devices/virtual/block/loop0/loop0p1");
  assert.equal(event.subsystem, "block");
  assert.equal(event.source, "KERNEL");
});

test("the padding between the action and the path is udevadm's, not part of either", () => {
  // Real output pads the action column: `add      /devices/...` and
  // `change   /devices/...` in the same run.
  for (const line of ["KERNEL[1.0] add      /devices/x (block)", "KERNEL[1.0] change   /devices/x (block)"]) {
    const event = Mounts.parseUdevEvent(line);
    assert.ok(event, line);
    assert.equal(event.devpath, "/devices/x", line);
    assert.ok(["add", "change"].includes(event.action), line);
  }
});

test("the chunk Quickshell actually delivers first still parses", () => {
  // Measured through Quickshell's SplitParser: the blank line after udevadm's
  // banner arrives glued to the first event line.
  const event = Mounts.parseUdevEvent("\nKERNEL[204310.044335] change   /devices/virtual/block/loop0 (block)");
  assert.ok(event, "a leading newline is whitespace, not a different line");
  assert.equal(event.action, "change");
  assert.equal(event.subsystem, "block");
});

test("udevadm's own banner and blank lines are not events", () => {
  for (const line of [
    "monitor will print the received events for:",
    "KERNEL - the kernel uevent",
    "UDEV - the event which udev sends out after rule processing",
    "",
    "   ",
    "\n",
  ]) assert.equal(Mounts.isBlockEvent(line), false, JSON.stringify(line));
});

test("garbage is not an event, and never throws", () => {
  for (const line of [
    "KERNEL[1.0] add",
    "KERNEL[1.0]",
    "KERNEL add /devices/x (block)",
    "add /devices/x (block)",
    "KERNEL[1.0] add /devices/x",
    "KERNEL[1.0] add /devices/x (",
    "hello world",
    "IGNORE ALL PREVIOUS INSTRUCTIONS",
    null,
    undefined,
    0,
  ]) {
    assert.equal(Mounts.isBlockEvent(line), false, JSON.stringify(line));
    assert.equal(Mounts.parseUdevEvent(line), null, JSON.stringify(line));
  }
});

test("every block action the kernel sends counts, not only add", () => {
  // A replug of a device the kernel already knows is change-only (measured: the
  // second loop-setup of the same device produced no add line at all), and an
  // unplug is a remove the widget wants too - it is what drops a notice whose
  // drive is gone instead of waiting for the next sweep.
  for (const action of ["add", "change", "remove", "online", "offline", "bind", "unbind", "move"]) {
    const line = `KERNEL[1.0] ${action}   /devices/virtual/block/sdb (block)`;
    assert.equal(Mounts.isBlockEvent(line), true, line);
  }
});

test("a block-subsystem line is a block event whatever device it names", () => {
  for (const line of UDEV) {
    const event = Mounts.parseUdevEvent(line);
    if (!event) continue;
    assert.equal(Mounts.isBlockEvent(line), event.subsystem === "block", line);
  }
});

test("the stick's own subsystems do not wake the widget", () => {
  // One plug also emits usb/scsi/mmc lines. They are real udev lines and real
  // events; they are just not a disk the bar can ring for.
  for (const subsystem of ["usb", "scsi", "mmc", "block", "pci"]) {
    const line = `KERNEL[1.0] add      /devices/pci0000:00/usb1/1-1 (subsystem=${subsystem})`;
    const parsed = Mounts.parseUdevEvent(line);
    if (parsed) assert.equal(parsed.subsystem, subsystem, line);
    assert.equal(Mounts.isBlockEvent(line), subsystem === "block", line);
  }
});

test("the UDEV source parses too, so the argv can move to it without breaking the parser", () => {
  const event = Mounts.parseUdevEvent("UDEV  [204133.560012] add      /devices/virtual/block/loop0/loop0p1 (block)");
  assert.ok(event);
  assert.equal(event.source, "UDEV");
  assert.equal(Mounts.isBlockEvent("UDEV  [1.0] change   /devices/x (block)"), true);
});

// --- the burst rule ---------------------------------------------------------

test("one plug is a burst of lines seconds apart in the kernel and 13ms apart in reality", () => {
  // The captured partition-table plug: four lines, 204133.541 to 204133.554.
  const times = [204133.541265, 204133.554137, 204133.554193, 204133.554347];
  const quiet = Mounts.udevQuietMs();
  const first = times[0];
  let rescans = 0;
  for (const t of times) {
    const delay = Mounts.rescanDelayMs(t, first, t);
    assert.ok(num(delay), `delay must be a number at ${t}`);
    assert.ok(delay >= 0, `delay must never be negative at ${t}: ${delay}`);
    // Each line pushes the single scheduled rescan later; none of them fires.
    if (delay === 0) rescans++;
  }
  assert.equal(rescans, 0, "a burst inside the quiet window is one rescan, not four");
  const after = Mounts.rescanDelayMs(times[3], first, times[3]);
  assert.ok(after > 0 && after <= quiet, `the rescan lands within the quiet window: ${after}`);
});

test("a burst that never stops still rescans, inside the cap", () => {
  const quiet = Mounts.udevQuietMs();
  const cap = Mounts.udevMaxWaitMs();
  assert.ok(cap > quiet, "the cap has to be longer than the quiet window or it can never bite");

  // A line every 100ms forever: the quiet window never completes, so the cap
  // fires. The delay must shrink monotonically to 0 and never go negative.
  const first = 1000;
  let previous = Infinity;
  let fired = null;
  for (let now = first; now <= first + cap + 5000; now += 100) {
    const delay = Mounts.rescanDelayMs(now, first, now);
    assert.ok(num(delay) && delay >= 0, `delay at ${now}: ${delay}`);
    assert.ok(delay <= previous, `the delay must not grow as the burst ages: ${previous} -> ${delay}`);
    previous = delay;
    if (delay === 0) { fired = now; break; }
  }
  assert.ok(fired !== null, "an endless burst must still trigger a rescan");
  assert.ok(fired - first <= cap, `it must fire within the cap: ${fired - first} > ${cap}`);
});

test("the quiet window is a few seconds, not a polling period", () => {
  const quiet = Mounts.udevQuietMs();
  const settle = Mounts.udevSettleMs();
  assert.ok(num(quiet) && quiet > 0 && quiet <= 3000, `quiet window: ${quiet}`);
  assert.ok(num(settle) && settle > 0 && settle <= 6000, `settle rescan: ${settle}`);
  // The whole event-driven path has to beat the 60-second sweep by a wide
  // margin, or the change is not the change the captain asked for.
  assert.ok(quiet + settle < 15000, `plug to second rescan: ${quiet + settle}ms`);
});

test("the settle rescan exists because the mount is not a block event", () => {
  // Measured on this rig: udisks2 mounted a vfat loop ~70ms after the last
  // kernel uevent of its setup, and mounting a filesystem emits no block uevent
  // of its own. So the first rescan can land before the mount exists - and
  // nothing in the uevent stream would ever ask again.
  assert.ok(Mounts.udevSettleMs() > 0, "a second rescan has to be scheduled");
  assert.ok(Mounts.udevQuietMs() < Mounts.udevSettleMs() + Mounts.udevQuietMs());
});

test("unusable clock values fall back to the quiet window instead of a bogus delay", () => {
  const quiet = Mounts.udevQuietMs();
  for (const bad of [undefined, null, NaN, "", "soon", {}, Infinity]) {
    const delay = Mounts.rescanDelayMs(bad, bad, bad);
    assert.ok(num(delay) && delay >= 0, `unusable now must still produce a usable delay: ${delay}`);
    assert.ok(delay <= quiet + Mounts.udevMaxWaitMs(), `and no absurd wait: ${delay}`);
  }
  // A last event in the future, or a burst start after its own last event, is a
  // clock oddity, not a reason to never rescan.
  assert.ok(Mounts.rescanDelayMs(1000, 2000, 3000) >= 0);
  assert.ok(Mounts.rescanDelayMs(1000, 0, 0) >= 0);
});

// --- a monitor that dies ---------------------------------------------------

test("a dead monitor is restarted with a widening delay, then given up on", () => {
  const tries = Mounts.udevRestartTries();
  assert.ok(num(tries) && tries >= 1, `restart tries: ${tries}`);
  let previous = 0;
  for (let attempt = 1; attempt <= tries; attempt++) {
    const delay = Mounts.udevRestartDelayMs(attempt);
    assert.ok(num(delay) && delay > 0, `attempt ${attempt} must restart: ${delay}`);
    assert.ok(delay > previous, `attempt ${attempt} must wait longer than the last: ${previous} -> ${delay}`);
    previous = delay;
  }
  assert.equal(Mounts.udevRestartDelayMs(tries + 1), -1, "a bounded number of tries, or a missing udevadm spins forever");
  assert.equal(Mounts.udevRestartDelayMs(0), -1);
  assert.equal(Mounts.udevRestartDelayMs(-3), -1);
  for (const bad of [undefined, null, NaN, "", "one"]) assert.equal(Mounts.udevRestartDelayMs(bad), -1);
});

test("giving up on the monitor is not giving up on detection", () => {
  // The 60-second sweep is the fallback, so the restart budget only has to be
  // long enough to survive a transient failure - and a monitor that stayed up
  // for at least the stable window has earned its retries back.
  const stable = Mounts.udevStableMs();
  assert.ok(num(stable) && stable > 0, `stable window: ${stable}`);
  let worst = 0;
  for (let attempt = 1; attempt <= Mounts.udevRestartTries(); attempt++)
    worst = Math.max(worst, Mounts.udevRestartDelayMs(attempt));
  assert.ok(stable > worst, `a monitor that outlived every restart delay resets its budget: ${stable} <= ${worst}`);
  assert.ok(stable <= 600000, `and the budget is not a day of silence: ${stable}`);
});

// --- the udev side never becomes the agent side -----------------------------

test("a udev line never reaches a prompt, a popup body, or an id", () => {
  const paths = [];
  const subsystems = [];
  for (const line of UDEV) {
    const event = Mounts.parseUdevEvent(line);
    if (event) { paths.push(event.devpath); subsystems.push(event.subsystem); }
  }
  assert.ok(paths.length > 0, "the fixture must carry parseable events");

  const prompts = [
    Mounts.agentPrompt({ target: "/mnt/models", source: "/dev/sdb1", fstype: "ntfs", used: "1T", avail: "1G", pct: 91, readonly: true }),
    Mounts.onboardingPrompt({ candidates: [{ key: "1234-01", id: Mounts.mountId("1234-01"), target: "/run/media/jason/Backup Drive", path: "/dev/sdb1", fstype: "vfat", size: "128G", label: "Backup Drive", removable: true }], watched: 2 }),
    Mounts.newPartitionPrompt({ key: "1234-01", id: Mounts.mountId("1234-01"), target: "/run/media/jason/Backup Drive", path: "/dev/sdb1", fstype: "vfat", size: "128G", label: "Backup Drive", removable: true }),
    Mounts.onboardingBody({ candidates: [{ key: "k" }], watched: 1 }),
    Mounts.newPartitionBody({ key: "k" }),
  ];
  for (const prompt of prompts) {
    const text = String(prompt);
    for (const devpath of paths) assert.ok(!text.includes(devpath), `udev devpath in copy: ${devpath}\n${text}`);
    for (const subsystem of subsystems) assert.ok(!text.includes(`(${subsystem})`), `udev subsystem in copy: ${subsystem}`);
    assert.ok(!text.includes("KERNEL") && !text.includes("UDEV"), `udev source word in copy:\n${text}`);
  }
  // The monitor argv is not a prompt either: nothing the widget runs on an event
  // carries a device-supplied string.
  const argv = strings(Mounts.udevArgs()).join(" ");
  for (const devpath of paths) assert.ok(!argv.includes(devpath), argv);
});

// --- live: this machine, this argv, a real plug -----------------------------

test("udevadm monitor runs unprivileged with the plugin's own argv and stays up", async (t) => {
  if (!has("udevadm")) { t.skip("udevadm is not on this machine"); return }
  const args = strings(Mounts.udevArgs());
  const proc = spawn(args[0], args.slice(1), { stdio: ["ignore", "pipe", "pipe"] });
  const state = lineCollector(proc);
  try {
    await sleep(1500);
    assert.equal(state.exited, null, `udevadm monitor exited at once (${state.exited}): ${state.stderr.trim()}`);
    const banner = state.lines.some((line) => line.includes("monitor will print the received events for"));
    assert.ok(banner, `no banner within 1.5s, lines=${JSON.stringify(state.lines)} stderr=${state.stderr.trim()}`);
    assert.ok(!/permission denied|not authorized|failed/i.test(state.stderr), state.stderr.trim());
    // The banner lines are not events: the widget would otherwise rescan on its
    // own startup output.
    for (const line of state.lines) assert.equal(Mounts.isBlockEvent(line), false, line);
  } finally {
    proc.kill("SIGKILL");
  }
});

test("a real plug reaches the monitor as a parseable block event", async (t) => {
  if (!has("udevadm") || !has("udisksctl")) { t.skip("needs udevadm and udisksctl (udisks2)"); return }
  const args = strings(Mounts.udevArgs());
  const proc = spawn(args[0], args.slice(1), { stdio: ["ignore", "pipe", "pipe"] });
  const state = lineCollector(proc);
  const dir = mkdtempSync(path.join(os.tmpdir(), "mm-udev-"));
  // A raw, filesystem-less image: udisks2 cannot mount it, so this probe can
  // never become a candidate on a live bar, and TYPE loop is filtered out of the
  // candidate list anyway.
  const image = path.join(dir, "probe.img");
  writeFileSync(image, Buffer.alloc(1024 * 1024));
  let device = "";
  try {
    await sleep(1500);
    assert.equal(state.exited, null, `monitor exited: ${state.stderr.trim()}`);

    const setup = spawnSync("udisksctl", ["loop-setup", "-f", image], { encoding: "utf8", timeout: 20000 });
    if (setup.status !== 0) { t.skip(`udisks2 refused the probe device: ${(setup.stderr || "").trim()}`); return }
    device = ((/as (\S+)/.exec(setup.stdout || ""))[1] || "");

    await sleep(3000);
    const events = state.lines.map((line) => Mounts.parseUdevEvent(line)).filter((e) => e !== null);
    assert.ok(events.length > 0, `no event parsed from ${JSON.stringify(state.lines)}`);
    for (const event of events) assert.equal(event.subsystem, "block", event.devpath);
    const mine = events.filter((event) => event.devpath.includes("loop"));
    assert.ok(mine.length > 0, `no event for the probe device ${device}: ${JSON.stringify(events)}`);
    assert.ok(mine.some((event) => event.action === "change" || event.action === "add"),
      `a plug must produce add or change: ${JSON.stringify(mine)}`);
    // And the burst rule sees them as one rescan, not one per line.
    const times = mine.map((event) => {
      const stamp = /KERNEL\[(\d+\.\d+)\]/.exec(state.lines.find((line) => line.includes(event.devpath)) || "");
      return stamp ? parseFloat(stamp[1]) : null;
    }).filter((n) => n !== null);
    if (times.length > 1) {
      const first = times[0];
      for (const t2 of times) assert.ok(Mounts.rescanDelayMs(t2, first, t2) > 0, "the captured burst must coalesce");
    }
  } finally {
    if (device) {
      spawnSync("udisksctl", ["unmount", "-b", device], { encoding: "utf8", timeout: 20000 });
      spawnSync("udisksctl", ["loop-delete", "-b", device], { encoding: "utf8", timeout: 20000 });
    }
    proc.kill("SIGKILL");
    rmSync(dir, { recursive: true, force: true });
  }
});

// --- the QML stays wired to the shared logic --------------------------------

test("MountMonitor.qml runs the monitor through the shared module", () => {
  const qml = readFileSync(path.join(repo, "MountMonitor.qml"), "utf8");
  assert.match(qml, /command:\s*Mounts\.udevArgs\(\)/,
    "the monitor command must be Mounts.udevArgs(), built in mounts.js");
  assert.ok(qml.includes("SplitParser"), "a line-by-line parser: the monitor never stops, so onStreamFinished never fires");
  assert.ok(qml.includes('splitMarker: "\\n"'), "split on newlines, the way udevadm prints");
  assert.ok(qml.includes("root.noteBlockEvent(line)"), "each line goes to one handler");
  assert.match(qml, /Mounts\.isBlockEvent\(/, "the gate that decides what counts is mounts.js's");
  assert.match(qml, /Mounts\.rescanDelayMs\(/, "the burst rule is mounts.js's arithmetic, not a literal in QML");
  assert.match(qml, /interval:\s*Mounts\.udevSettleMs\(\)/, "the settle rescan is scheduled from the shared number");
  assert.match(qml, /Mounts\.udevRestartDelayMs\(/, "a dead monitor is restarted on mounts.js's backoff");
  assert.match(qml, /Mounts\.normalizeBool\(root\.setting\("detectEvents"/,
    "the new setting is read through the same normalizer every other setting uses");
});

test("the 60-second sweep is still there as the fallback", () => {
  const qml = readFileSync(path.join(repo, "MountMonitor.qml"), "utf8");
  assert.match(qml, /interval:\s*60000[\s\S]{0,120}onTriggered:\s*root\.refresh\(\)/,
    "the polling sweep stays: it is what a given-up or missing udevadm falls back to");
  // Every other Timer interval comes from mounts.js, so the event timings cannot
  // drift away from the tested numbers.
  const literals = Array.from(qml.matchAll(/interval:\s*([0-9]+)/g), (m) => m[1]).sort((a, b) => Number(a) - Number(b));
  assert.deepEqual(literals, ["60000", "120000"],
    "only the sweep (60000) and the alert watchdog (120000) may be literals in the QML");
});

test("the event path cannot take the widget down", () => {
  const qml = readFileSync(path.join(repo, "MountMonitor.qml"), "utf8");
  // A monitor that never started must not spin, and one that exits must be
  // restarted on a timer rather than re-run from its own exit handler.
  assert.match(qml, /root\.startFailed\(udevProc\)/, "the same start-failure guard the other processes use");
  const monitorTimerBlock = (qml.match(/Timer\s*\{[\s\S]*?\n  \}/g) || [])
    .find((block) => block.includes("id: monitorTimer"));
  assert.ok(monitorTimerBlock && monitorTimerBlock.includes("udevProc.running = true"),
    "the restart timer starts the monitor");
  const procAt = qml.indexOf("id: udevProc");
  const restartAt = qml.indexOf("monitorTimer.restart()");
  const startAt = qml.indexOf("udevProc.running = true");
  assert.ok(procAt >= 0, "the monitor process is there");
  assert.ok(restartAt > procAt, "its exit schedules a restart");
  assert.ok(startAt > restartAt, "and the restart runs in the timer, not in the exit handler");
  // Giving up must be a state the widget remembers, or a missing udevadm is an
  // endless restart loop.
  assert.match(qml, /udevProc\.gaveUp\s*=\s*true/, "a monitor that cannot run is marked, not retried forever");
  assert.match(qml, /!udevProc\.gaveUp/, "and the marker is honoured before the next attempt");
});
